"""Summarize the Phase 3 runs from their tracked JSON into one Markdown table.

Reads evaluation/reports/experiments/phase3/<run>/latest.json (and v1-baseline). Fails loudly
on missing, failed or non-label-blind runs instead of printing zeros. Standard library only.

    python evaluation/scripts/summarize_phase3.py            # writes phase3/SUMMARY.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / "evaluation" / "reports" / "experiments" / "phase3"


def rows() -> list[dict]:
    out = []
    for run in sorted(p for p in BASE.iterdir() if (p / "latest.json").exists()):
        data = json.loads((run / "latest.json").read_text(encoding="utf-8"))
        if not data.get("label_blind"):
            sys.exit(f"{run.name}: not label-blind")
        sp = data["system_prompt"]
        for cfg in data["configs"]:
            if cfg["status"] != "completed":
                sys.exit(f"{run.name}/{cfg['config']}: {cfg['status']} ({cfg.get('reason')})")
            m, cases = cfg["metrics"], cfg["per_case"]
            multi = [c for c in cases if c["label"] == "synthetic-multifile" and c["expected"]]
            ai_failed = sum(c["ai_status"] == "failed" for c in cases)
            out.append({
                "run": run.name, "dataset": data["dataset"], "config": cfg["config"],
                "prompt": sp.get("version", "v1") if cfg["config"] != "static" else "-",
                "context": sp.get("context", "changed") if cfg["config"] != "static" else "-",
                "tp": m["tp"], "fn": m["fn"], "fp": m["fp"],
                "recall": m["recall"], "precision": m["precision"],
                "clean_fp": m["clean_case_false_positive_rate"],
                "multi": f"{sum(c['tp'] for c in multi)}/{sum(c['expected'] for c in multi)}" if multi else "-",
                "ai_failed": ai_failed if cfg["config"] != "static" else "-",
                "p50_ms": m["latency_ms_p50"], "in_tok": m["mean_input_tokens"], "out_tok": m["mean_output_tokens"],
                "found": sorted(c["id"] for c in cases if c["tp"]),
            })
    return out


def fmt(v) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.3f}" if v < 10 else f"{v:.0f}"
    return str(v)


def main() -> None:
    rs = rows()
    cols = ["run", "dataset", "config", "prompt", "context", "tp", "fn", "fp", "recall", "precision",
            "clean_fp", "multi", "ai_failed", "p50_ms", "in_tok", "out_tok"]
    lines = ["# Phase 3 results (generated)", "",
             "Generated by `evaluation/scripts/summarize_phase3.py` from each run's `latest.json`. "
             "`multi` = multi-file defects found / present. `ai_failed` = cases whose model call failed "
             "(counted as failures, never as zero findings). Model: qwen2.5-coder:3b via Ollama, temperature 0.", "",
             "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(r[c]) for c in cols) + " |" for r in rs]
    lines += ["", "## Defects found per run", ""]
    lines += [f"- **{r['run']} / {r['config']}**: {', '.join(r['found']) or 'none'}" for r in rs]
    (BASE / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
