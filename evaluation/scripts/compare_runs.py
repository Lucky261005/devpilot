"""Build the label-blind comparison table from saved run files (no model calls).

Reads only tracked files (each run's latest.json and details.json), never eval.db, and stops with an
error if any input is missing, not label-blind, incomplete, or inconsistent.

Usage (any Python 3.12+, from the repository root):
    python evaluation/scripts/compare_runs.py            # writes evaluation/reports/experiments/COMPARISON.md
    python evaluation/scripts/compare_runs.py --stdout   # print instead
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

EXP = Path(__file__).resolve().parents[1] / "reports" / "experiments"
GROUPS = [
    ("Original analyzers (Ruff + Bandit)", "label-blind", ["static"]),
    ("AI-only, single-step", "label-blind", ["ai-single-1", "ai-single-2", "ai-single-3"]),
    ("AI-only, two-step", "label-blind", ["ai-two-1", "ai-two-2", "ai-two-3"]),
    (
        "Combined single-step, original analyzers",
        "label-blind",
        ["combined-single-1", "combined-single-2", "combined-single-3"],
    ),
    ("Combined two-step, original analyzers", "label-blind", ["combined-two-1", "combined-two-2", "combined-two-3"]),
    ("Improved analyzers (+SIM115, +DP001)", "label-blind-static-v2", ["static"]),
    (
        "Combined single-step, improved analyzers",
        "label-blind-static-v2",
        ["combined-single-1", "combined-single-2", "combined-single-3"],
    ),
    ("Combined two-step, improved analyzers", "label-blind-static-v2", ["combined-two-1"]),
]


class ArtifactError(SystemExit):
    pass


def load(d: Path) -> tuple[dict, dict]:
    """Read a run's tracked files and check they agree. Never falls back to zeros."""
    for name in ("latest.json", "details.json"):
        if not (d / name).is_file():
            raise ArtifactError(f"missing {d / name}; export it with evaluation/scripts/run_details.py")
    r = json.loads((d / "latest.json").read_text(encoding="utf-8"))
    det = json.loads((d / "details.json").read_text(encoding="utf-8"))
    if r.get("label_blind") is not True:
        raise ArtifactError(f"{d} is not a label-blind run")
    c = r["configs"][0]
    if c.get("status") != "completed":
        raise ArtifactError(f"{d}: run status is {c.get('status')!r}, not completed")
    if det["jobs"] != c["cases"] or not all(x["label_blind"] for x in det["cases"]):
        raise ArtifactError(f"{d}: details.json does not match latest.json (jobs/label-blind)")
    by_case = {x["case_id"]: x for x in det["cases"]}
    for p in c["per_case"]:
        if len(p["predictions"]) != len(by_case[p["id"]]["findings"]):
            raise ArtifactError(f"{d}: findings for {p['id']} differ between latest.json and details.json")
    return r, det


def row(folder: str, run: str) -> dict:
    d = EXP / folder / run
    r, det = load(d)
    c = r["configs"][0]
    m = c["metrics"]
    stats = [x["stats"] for x in det["cases"]]
    ai = [s.get("ai", {}) for s in stats]
    model_tp = sum(1 for p in c["per_case"] for x in p["predictions"] if x["source"] == "ai")
    return {
        "run": run,
        "tp": m["tp"],
        "recall": m["recall"],
        "precision": m["precision"],
        "fp": m["fp"],
        "fp_clean": sum(1 for p in c["per_case"] if not p["expected"] and p["fp"]),
        "calls": sum(a.get("attempts") or 0 for a in ai),
        "failures": [a.get("reason") for a in ai if a.get("status") == "failed"],
        "returned": sum(a.get("returned") or 0 for a in ai),
        "accepted": sum(a.get("accepted") or 0 for a in ai),
        "rejected": sum(len(a.get("rejected", [])) for a in ai),
        "dedup": sum(s.get("duplicates_dropped", 0) for s in stats),
        "model_kept": model_tp,
        "p50": m["latency_ms_p50"],
        "tok": (m["mean_input_tokens"], m["mean_output_tokens"]),
        "found": {p["id"] for p in c["per_case"] if p["tp"]},
    }


def f(v, fmt="{:.3f}"):
    return "—" if v is None else fmt.format(v)


def main() -> None:
    print("# Label-blind comparison (generated by `evaluation/scripts/compare_runs.py`)\n")
    print(
        "Dataset v1: 17 synthetic cases, 13 seeded defects, 4 clean cases (`clean-rename-variable`, "
        "`clean-add-typed-helper`, `clean-context-manager-refactor`, `clean-safe-subprocess`). "
        "Model `qwen2.5-coder:3b` (Ollama). Every run below has `label_blind: true`.\n"
    )
    print(
        "| Configuration | Run | Detected /13 | Recall | Precision | False positives (on clean cases) | Model calls | Failures | Model findings returned / accepted / rejected | Duplicates removed | Model findings kept | p50 latency | Tokens in / out |"
    )
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    all_rows = {}
    for label, folder, runs in GROUPS:
        for run in runs:
            x = row(folder, run)
            all_rows[(label, run)] = x
            tok = "—" if x["tok"][0] is None else f"{x['tok'][0]:.0f} / {x['tok'][1]:.0f}"
            fails = f"{len(x['failures'])}" + (f" ({x['failures'][0]})" if x["failures"] else "")
            print(
                f"| {label} | {folder}/{run} | {x['tp']} | {f(x['recall'])} | {f(x['precision'], '{:.2f}')} | "
                f"{x['fp']} ({x['fp_clean']}/4) | {x['calls']} | {fails} | {x['returned']} / {x['accepted']} / {x['rejected']} | "
                f"{x['dedup']} | {x['model_kept']} | {x['p50'] / 1000:.2f} s | {tok} |"
            )
    base = all_rows[("Original analyzers (Ruff + Bandit)", "static")]["found"]
    improved = all_rows[("Improved analyzers (+SIM115, +DP001)", "static")]["found"]
    print(
        "\n**Unique valid model findings** (true positives not found by the analyzers in the same configuration): "
        + str(
            sum(
                len(x["found"] - (improved if "improved" in k[0] else base))
                for k, x in all_rows.items()
                if "Combined" in k[0]
            )
        )
    )
    print(
        f"\nOriginal analyzers found {len(base)}/13; improved analyzers found {len(improved)}/13; "
        f"newly detected: {', '.join(sorted(improved - base))}; lost: {', '.join(sorted(base - improved)) or 'none'}."
    )


if __name__ == "__main__":
    import contextlib
    import io

    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        main()
    if "--stdout" in sys.argv:
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
        sys.stdout.write(buf.getvalue())
    else:
        out = EXP / "COMPARISON.md"
        out.write_text(buf.getvalue(), encoding="utf-8")  # explicit UTF-8 on every OS
        print(f"wrote {out.relative_to(EXP.parents[2])}")
